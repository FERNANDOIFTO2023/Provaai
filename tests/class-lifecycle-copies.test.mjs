import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

test('class lifecycle and copies enforce ownership, independent snapshots, audited deletion and one-year retention', async () => {
  const db = new PGlite();
  const file = name => readFile(new URL('../' + name, import.meta.url), 'utf8');
  const owner = randomUUID(), recipient = randomUUID(), outsider = randomUUID();
  const room = randomUUID(), pupil = randomUUID(), exam = randomUUID(), destination = randomUUID();
  const asUser = async id => { await db.exec('reset role; set role authenticated'); await db.query("select set_config('test.uid',$1,false)", [id]); };
  const scalar = async (sql, args = []) => Object.values((await db.query(sql, args)).rows[0])[0];
  try {
    await db.exec(`create role anon; create role authenticated; create schema auth;
      create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz);
      create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
      grant usage on schema auth to authenticated;`);
    const schema = await file('public/schema.sql');
    await db.exec(schema.slice(0, schema.indexOf('insert into storage.buckets')) + 'commit;');
    await db.exec("alter table sala_templates add processing_status text default 'ready';");
    for (const migration of ['20261105162821_teacher_template_defaults.sql','20261105220532_teacher_exam_batch.sql',
      '20261105235000_recovery_and_archived_students.sql','20261106161318_reactivate_student_in_class.sql','20261106181131_class_lifecycle_and_copies.sql'])
      await db.exec(await file('supabase/migrations/' + migration));
    for (const [id, email] of [[owner, 'owner@example.com'], [recipient, 'teacher@example.com'], [outsider, 'other@example.com']])
      await db.query('insert into auth.users values($1,$2,now())', [id, email]);
    await asUser(owner);
    await db.query("insert into sala_classes(id,user_id,name,grade,subject,icon) values($1,$2,'Turma original','7','Matemática','sparkles')", [room, owner]);
    await db.query("insert into sala_students(id,user_id,class_id,name,code,difficulties) values($1,$2,$3,'Aluno original','A001','Frações')", [pupil, owner, room]);
    await db.query("insert into sala_exams(id,user_id,class_id,student_id,title,subject,topics,question_count,content,profile_snapshot) values($1,$2,$3,$4,'Prova original','Matemática','Frações',1,'{\"questions\":[]}','{}')", [exam, owner, room, pupil]);
    await db.query('insert into sala_recovery_students(user_id,student_id) values($1,$2)', [owner,pupil]);
    await db.query('insert into sala_generation_jobs(exam_id,user_id) values($1,$2)', [exam,owner]);
    await assert.rejects(db.query('select sala_set_class_active($1,false)', [room]), /Aguarde a geração/);
    await db.query("update sala_generation_jobs set status='done' where exam_id=$1",[exam]);
    const invitation = randomUUID();
    await db.query("select sala_send_copy($1,'class',$2,' Teacher@Example.com ')", [invitation, room]);
    assert.equal(await scalar("select sala_send_copy($1,'class',$2,'teacher@example.com')", [invitation,room]), invitation);
    await assert.rejects(db.query("select sala_send_copy($1,'class',$2,'other@example.com')",[invitation,room]), /já utilizado/);
    await assert.rejects(db.query('select payload from sala_copy_invitations'), /permission denied/);
    await db.query("update sala_students set name='Nome alterado depois' where id=$1", [pupil]);
    await asUser(outsider);
    assert.equal(await scalar('select count(*)::int from sala_copy_invitations'), 0);
    await assert.rejects(db.query('select sala_accept_copy($1,null)', [invitation]), /não disponível/);
    await assert.rejects(db.query('select sala_set_class_active($1,false)',[room]), /não encontrada/);
    await asUser(recipient);
    assert.equal(await scalar('select count(*)::int from sala_classes'), 0);
    const copy = await scalar('select sala_accept_copy($1,null)',[invitation]);
    assert.notEqual(copy,room);
    assert.equal(await scalar('select sala_accept_copy($1,null)',[invitation]),copy);
    assert.equal(await scalar('select count(*)::int from sala_classes'),1);
    assert.equal(await scalar('select icon from sala_classes where id=$1',[copy]),'sparkles');
    assert.equal(await scalar('select name from sala_students where class_id=$1',[copy]),'Aluno original');
    assert.equal(await scalar('select count(*)::int from sala_exams'),0);
    await db.query("update sala_students set difficulties='Edição da cópia' where class_id=$1",[copy]);
    await db.query("insert into sala_classes(id,user_id,name,grade,subject) values($1,$2,'Destino','8','Ciências')",[destination,recipient]);
    await db.query("insert into sala_students(user_id,class_id,name,code) values($1,$2,'Outro aluno','A009')",[recipient,destination]);
    await asUser(owner);
    assert.equal(await scalar('select difficulties from sala_students where id=$1',[pupil]),'Frações');
    const individual = randomUUID(), revoked = randomUUID();
    await db.query("select sala_send_copy($1,'student',$2,'teacher@example.com')",[individual,pupil]);
    await db.query("select sala_send_copy($1,'class',$2,'teacher@example.com')",[revoked,room]);
    await db.query('select sala_cancel_copy($1)',[revoked]);
    await asUser(recipient);
    await assert.rejects(db.query('select sala_accept_copy($1,null)',[revoked]),/não disponível/);
    await assert.rejects(db.query('select sala_accept_copy($1,$2)',[individual,room]),/turma ativa da sua conta/);
    await db.query('select sala_set_class_active($1,false)',[destination]);
    await assert.rejects(db.query('select sala_accept_copy($1,$2)',[individual,destination]),/turma ativa/);
    await db.query('select sala_set_class_active($1,true)',[destination]);
    await db.query('select sala_accept_copy($1,$2)',[individual,destination]);
    assert.equal(await scalar("select code from sala_students where class_id=$1 and name='Nome alterado depois'",[destination]),'A010');
    await asUser(owner);
    await assert.rejects(db.query("update sala_classes set archived_at=now() where id=$1",[room]),/permission denied/);
    await assert.rejects(db.query('delete from sala_classes where id=$1',[room]),/permission denied/);
    await assert.rejects(db.query("select sala_delete_class($1,' ')",[room]),/motivo/);
    await db.query('select sala_set_class_active($1,false)',[room]);
    const date = await scalar('select archived_at from sala_classes where id=$1',[room]);
    await db.query('select sala_set_class_active($1,false)',[room]);
    assert.equal(String(await scalar('select archived_at from sala_classes where id=$1',[room])),String(date));
    await assert.rejects(db.query("insert into sala_students(user_id,class_id,name,code) values($1,$2,'Bloqueado','A002')",[owner,room]),/Reative a turma/);
    await db.query('update sala_students set archived_at=now() where id=$1',[pupil]);
    await assert.rejects(db.query('select sala_reactivate_student($1,$2)',[pupil,room]),/Reative a turma/);
    await assert.rejects(db.query('select sala_purge_inactive_classes()'),/permission denied/);
    await db.query('select sala_set_class_active($1,true)',[room]);
    await db.query('select sala_reactivate_student($1,$2)',[pupil,room]);
    await db.query('select sala_set_class_active($1,false)',[room]);
    await db.exec('reset role');
    await db.query("update sala_classes set archived_at=now()-interval '1 year 1 day',deletion_due_at=now()-interval '1 day' where id=$1",[room]);
    await asUser(owner);
    await assert.rejects(db.query('select sala_set_class_active($1,true)',[room]),/prazo de um ano/);
    await db.exec('reset role');
    assert.equal(await scalar('select sala_purge_inactive_classes()'),1);
    assert.equal(await scalar('select count(*)::int from sala_students where user_id=$1',[owner]),0);
    assert.equal(await scalar('select count(*)::int from sala_exams where user_id=$1',[owner]),0);
    assert.equal(await scalar('select automatic from sala_class_deletions where class_id=$1',[room]),true);
    assert.equal(await scalar('select count(*)::int from sala_classes where id=$1',[copy]),1);
    await asUser(recipient);
    await db.query("select sala_delete_class($1,'Turma de teste encerrada')",[copy]);
    assert.equal(await scalar('select reason from sala_class_deletions where class_id=$1',[copy]),'Turma de teste encerrada');
    await db.exec('reset role; set role anon');
    await assert.rejects(db.query('select sala_accept_copy($1,null)',[invitation]),/permission denied/);
  } finally { await db.close(); }
});
